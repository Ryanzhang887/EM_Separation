"""Main and appendix figures for the fixed-separation and d=10^6 experiments."""

import json
import numpy as np
import matplotlib.pyplot as plt

from .plot_style import RC, WIDTH, component_style, zero_line
from .diagnostic_figures import generate_diagnostic_figures


def select(runs, **criteria):
    return sorted([r for r in runs if all(r["config"][k] == v for k, v in criteria.items())],
                  key=lambda r: r["config"]["seed"])


def save(fig, path):
    fig.savefig(path, bbox_inches="tight", metadata={"Creator": "experiments.summarize"})
    plt.close(fig)


def fixed_separation_trajectories(runs, path):
    dims = sorted({r["config"]["dimension"] for r in runs})
    seeds = sorted({r["config"]["seed"] for r in runs})
    height = 2.65 if len(seeds) == 1 else 6.3
    fig, axes = plt.subplots(len(seeds), len(dims), figsize=(WIDTH, height), squeeze=False)
    for col, d in enumerate(dims):
        ylim = max(max(h["orthogonal_norms"]) for r in select(runs, dimension=d) for h in r["history"])
        for row, seed in enumerate(seeds):
            r = select(runs, dimension=d, seed=seed)[0]
            x = np.array([h["parallel_means"] for h in r["history"]])[:, :, 0]
            y = np.array([h["orthogonal_norms"] for h in r["history"]])
            ax = axes[row, col]
            for k in range(x.shape[1]):
                style = component_style(k)
                ax.plot(x[:, k], y[:, k], **style)
                ax.plot(x[0, k], y[0, k], marker="x", color=".6", markersize=3,
                        markeredgewidth=.6, linestyle="none")
                ax.plot(x[-1, k], y[-1, k], marker="o", color=style["color"],
                        alpha=.65, markersize=3, linestyle="none")
            delta = r["separation"]
            ax.scatter([delta / 2, -delta / 2], [0, 0], color="red", marker="*",
                       s=45, zorder=5, linewidths=0, label=r"true $\mu_j^*$")
            zero_line(ax)
            ax.set_title(rf"$d={d}$, seed {seed}", loc="left")
            ax.set_ylim(-.045 * ylim, 1.1 * ylim)
            ax.set_xlabel(r"$\mu_{i,1}$")
            ax.set_ylabel(r"$\|\mu_{i,2:d}\|_2$")
            if row == 0:
                ax.legend(loc="best")
    fig.tight_layout(h_pad=1, w_pad=1.4)
    save(fig, path)


def generate_figures(runs, out, diagnostic_path):
    plt.rcParams.update(RC)
    fixed = [r for r in runs if r["suite"] == "fixed_separation"]
    high_dimensional = [r for r in runs if r["suite"] == "high_dimension"]
    if len(runs) != 12 or any(len(group) != 6 for group in [fixed, high_dimensional]):
        raise ValueError("The fixed-separation and d=10^6 protocols each require six completed runs")
    if {(r["config"]["dimension"], r["config"]["seed"]) for r in fixed} != {
            (d, seed) for d in [10, 500] for seed in [0, 1, 2]}:
        raise ValueError("Expected dimensions 10 and 500, each with seeds 0, 1, 2")
    if {(r["config"]["dimension"], r["config"]["name"], r["config"]["seed"]) for r in high_dimensional} != {
            (1000000, name, seed) for name in ["power_045", "sqrt_10"] for seed in [0, 1, 2]}:
        raise ValueError("Expected both d=10^6 separations, each with seeds 0, 1, 2")
    entries = []
    for filename, group, placement in [
        ("main_trajectories.pdf", select(fixed, seed=0), "main text"),
        ("fixed_separation_trajectories.pdf", fixed, "appendix"),
    ]:
        fixed_separation_trajectories(group, out / filename)
        entries.append({"file": filename, "runs": [r["suite"] + "/" + r["run_id"] for r in group],
                        "metrics": ["parallel_means", "orthogonal_norms"], "placement": placement,
                        "description": "Fixed-separation experiment at d=10,500 with Delta=6"})
    entries.extend(generate_diagnostic_figures(high_dimensional, diagnostic_path, out))
    for entry in entries:
        entry.setdefault("placement", "appendix")
    expected = {r["suite"] + "/" + r["run_id"] for r in runs}
    displayed = {rid for entry in entries for rid in entry["runs"]}
    if displayed != expected:
        raise ValueError("Figure coverage differs from the selected fixed-separation and d=10^6 runs")
    (out / "figure_manifest.json").write_text(json.dumps({
        "scope": "Fixed-separation experiment and fitted-mean/weight trajectories at d=10^6",
        "main_figure_seed": 0,
        "main_figure_selection": "First of the fixed seed list 0, 1, 2; all three seeds appear in the appendix",
        "d1e6_metrics": ["parallel_means", "orthogonal_norms", "weights"],
        "protocol": "Fixed separation at d=10,500; separation scaling at d=10^6. Parameters are specified in configs/.",
        "reproduction_status": "All published figures are generated by this code; all seed outcomes are shown",
        "total_unique_runs": len(expected), "figure_count": len(entries),
        "plot_style": "experiments/plot_style.py",
        "figures": entries}, indent=2) + "\n")
    return entries
